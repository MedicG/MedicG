"""Build assets/css/icons.css: Tabler outline icons used by the app as CSS masks (no web font)."""
import re, sys, urllib.parse
from pathlib import Path
src = Path(sys.argv[1]); repo = Path(sys.argv[2])
names = sorted(set(re.findall(r"\bti-([a-z0-9]+(?:-[a-z0-9]+)*)", "\n".join(p.read_text(errors="ignore") for p in [repo / "index.html", *sorted((repo / "assets/js").glob("*.js"))]))))
aliases = {"notes-medical": "notes"}
rules, missing = [], []
for name in names:
    f = src / f"{aliases.get(name, name)}.svg"
    if not f.exists():
        missing.append(name); continue
    svg = re.sub(r"<!--.*?-->", "", f.read_text(), flags=re.S)
    svg = re.sub(r"\s+", " ", svg).replace("> <", "><").strip()
    svg = svg.replace(' width="24" height="24"', "").replace('stroke="currentColor"', 'stroke="#000"')
    data = urllib.parse.quote(svg, safe=" =:/;,'\"-.")
    data = data.replace('"', "'")
    rules.append(f'.ti-{name}{{--ti:url("data:image/svg+xml,{data}")}}')
head = ("/* Tabler Icons (MIT, https://tabler.io) — only the icons used by Medic G, drawn as CSS masks.\n"
        "   Generated by tools/build_icons.py; do not edit by hand. */\n"
        ".ti{display:inline-block;width:1em;height:1em;line-height:1;vertical-align:-.125em;font-style:normal;flex:none}"
        ".ti:before{content:\"\";display:block;width:100%;height:100%;background-color:currentColor;"
        "-webkit-mask:var(--ti) center/100% 100% no-repeat;mask:var(--ti) center/100% 100% no-repeat}\n")
(repo / "assets/css/icons.css").write_text(head + "\n".join(rules) + "\n")
print(len(rules), "icons; missing:", missing)
