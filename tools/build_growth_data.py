"""Build assets/js/growth-data.js from the official WHO tables.

Sources (WHO GitHub repositories, LMS parameters):
  WHO Child Growth Standards 2006 (0-5 years):  WorldHealthOrganization/anthro  data-raw/growthstandards/*anthro.txt
  WHO Growth Reference 2007 (5-19 years):       WorldHealthOrganization/anthroplus data-raw/growthstandards/*who2007.txt
The Ministerio de Salud Pública del Ecuador uses these WHO standards and references for its growth charts.
Usage: python3 tools/build_growth_data.py <anthro/data-raw/growthstandards> <anthroplus/data-raw/growthstandards>
"""
import json, sys
from pathlib import Path

DAYS_PER_MONTH = 30.4375


def read(path):
    rows = []
    lines = Path(path).read_text().strip().splitlines()
    head = lines[0].split("\t")
    for line in lines[1:]:
        parts = dict(zip(head, line.split("\t")))
        rows.append(parts)
    return rows


def lms(row):
    return [round(float(row["l"]), 4), round(float(row["m"]), 4), round(float(row["s"]), 5)]


def monthly_from_daily(rows, sex, months):
    """Monthly LMS. Month 24 uses day 731 (first day measured standing), as in the WHO 2-5 years tables."""
    by_day = {int(r["age"]): r for r in rows if r["sex"] == str(sex)}
    return [lms(by_day[min(731 if m == 24 else round(m * DAYS_PER_MONTH), max(by_day))]) for m in range(months + 1)]


def day_lms(rows, sex, day):
    return lms(next(r for r in rows if r["sex"] == str(sex) and int(r["age"]) == day))


def monthly(rows, sex, start, end):
    by_month = {int(r["age"]): r for r in rows if r["sex"] == str(sex)}
    return [lms(by_month[m]) for m in range(start, end + 1)]


def by_size(rows, sex, key, start, end, step):
    table = {round(float(r[key]), 1): r for r in rows if r["sex"] == str(sex)}
    out, x = [], start
    while x <= end + 1e-9:
        out.append(lms(table[round(x, 1)]))
        x += step
    return out


def main(std_dir, ref_dir):
    std, ref = Path(std_dir), Path(ref_dir)
    wei, lenh, bmi, hc = (read(std / f) for f in ("weianthro.txt", "lenanthro.txt", "bmianthro.txt", "hcanthro.txt"))
    wfl, wfh = read(std / "wflanthro.txt"), read(std / "wfhanthro.txt")
    wfa07, hfa07, bfa07 = (read(ref / f) for f in ("wfawho2007.txt", "hfawho2007.txt", "bfawho2007.txt"))
    data = {"source": "OMS: Patrones de Crecimiento Infantil 2006 (0-5 años) y Referencia de Crecimiento 2007 (5-19 años). Usados por el MSP del Ecuador.",
            "age": {}, "size": {}}
    for sex, key in ((1, "m"), (2, "f")):
        data["age"][key] = {
            # Index = age in completed months. WHO 2006 standards up to 60 months, WHO 2007 references after.
            "wfa": monthly_from_daily(wei, sex, 60) + monthly(wfa07, sex, 61, 120),
            "hfa": monthly_from_daily(lenh, sex, 60) + monthly(hfa07, sex, 61, 228),
            "bfa": monthly_from_daily(bmi, sex, 60) + monthly(bfa07, sex, 61, 228),
            "hcfa": monthly_from_daily(hc, sex, 60),
            # Recumbent length at exactly 24 months (day 730): end of the 0-2 years charts.
            "len24": {"hfa": day_lms(lenh, sex, 730), "bfa": day_lms(bmi, sex, 730)},
        }
        data["size"][key] = {
            "wfl": {"start": 45, "step": 0.5, "lms": by_size(wfl, sex, "length", 45, 110, 0.5)},
            "wfh": {"start": 65, "step": 0.5, "lms": by_size(wfh, sex, "height", 65, 120, 0.5)},
        }
    out = Path(__file__).resolve().parents[1] / "assets/js/growth-data.js"
    out.write_text("/* Generated by tools/build_growth_data.py from the official WHO tables. Do not edit. */\n"
                   "window.WHO_GROWTH=" + json.dumps(data, separators=(",", ":")) + ";\n")
    print(out, out.stat().st_size, "bytes")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
